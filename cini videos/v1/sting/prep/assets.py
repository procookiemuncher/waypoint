"""Inline the real app icon (mac-version/app/icon.svg) into data/icon.js so the page scales
the actual file instead of a redrawn copy, and never has to fetch it."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))

with open(os.path.join(REPO, "mac-version", "app", "icon.svg")) as f:
    svg = f.read().strip()
with open(os.path.join(HERE, "..", "data", "icon.js"), "w") as f:
    f.write("// generated by prep/assets.py from mac-version/app/icon.svg, don't edit by hand\n")
    f.write("window.ICON_SVG = " + json.dumps(svg) + ";\n")
print("icon.js written,", len(svg), "chars")
