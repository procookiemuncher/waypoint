"""Everything the trailer says about the app's content, pulled from the app's own code.

Routes go through backend.routes.summary() (the same call the app's route list makes) with the
snap cache only, so the drawn lines are the real road-snapped ones and the miles/minutes match
the cards. Cities, spots and places come from core/destinations.json + core/places.json, and a
route without a city gets one the way app.js cityOf() does it (nearest within 100 km of its end).

    .venv/bin/python "cini videos/v2/trailer/prep/library.py"   ->  data/library.js
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "core"))
os.environ["VALHALLA_BASE_URL"] = "http://127.0.0.1:9"  # cache or bust, never the network

from backend.destinations import city_info, load_catalog, spot_places  # noqa: E402
from backend.routes import route_files, summary  # noqa: E402


def dist(a, b):
    """Same haversine as app.js dist()."""
    R = 6371000
    la1, la2 = math.radians(a[0]), math.radians(b[0])
    dla, dlo = la2 - la1, math.radians(b[1] - a[1])
    h = math.sin(dla / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin(dlo / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))


catalog = load_catalog()
cities = city_info(catalog)
with open(os.path.join(REPO, "core", "places.json")) as f:
    places = [{"id": k, **v} for k, v in json.load(f).items()]
places += [{"id": k, **v} for k, v in spot_places(catalog).items()]


def city_of(lat, lon):
    cands = [(n, c["lat"], c["lon"]) for n, c in cities.items()]
    cands += [(p["region"], p["lat"], p["lon"]) for p in places if p.get("region")]
    best, bd = "Elsewhere", 100_000
    for n, la, lo in cands:
        d = dist((lat, lon), (la, lo))
        if d < bd:
            best, bd = n, d
    return best


routes = {}
for path in route_files():
    s = summary(path)
    if len(s["line"]) < 2:
        print(f"  skip {s['id']}: no line")
        continue
    s["city"] = s.get("city") or city_of(*s["line"][-1])
    routes[s["id"]] = s
    print(f"{s['id']:40} {s['city']:16} {len(s['line']):5} pts {s['meters'] / 1609.34:6.1f} mi {s['seconds'] / 60:6.1f} min")
for p in places:
    p["city"] = p.get("region") or city_of(p["lat"], p["lon"])

spots = sum(len(c.get("spots", [])) for c in catalog.values())
continents = {c["continent"] for c in catalog.values()}
continents = {"Asia" if c == "Middle East" else c for c in continents}  # Dubai is in Asia
totals = {"cities": len(catalog), "spots": spots, "countries": len({c["country"] for c in catalog.values()}),
          "continents": len(continents), "routes": len(routes)}
print("totals", totals)

out = {"routes": routes, "cities": {n: {**cities[n], "spots": catalog[n].get("spots", []),
                                        "airportInfo": catalog[n].get("airport")} for n in cities},
       "places": places, "totals": totals}
with open(os.path.join(HERE, "..", "data", "library.js"), "w") as f:
    f.write("// generated by prep/library.py from core/routes, core/destinations.json, core/places.json\n")
    f.write("window.LIB = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
