"""World base map for the trailer: Natural Earth 1:50m land + country borders (public domain), from
the world-atlas TopoJSON, fetched once into cache/world/ and baked into data/world.js as lon/lat
rings. Nothing is fetched at render time.

    .venv/bin/python prep/world.py
"""
import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CACHE = os.path.join(ROOT, "cache", "world")
SRC = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/{}.json"


def fetch(name):
    os.makedirs(CACHE, exist_ok=True)
    p = os.path.join(CACHE, name + ".json")
    if not os.path.exists(p):
        with urllib.request.urlopen(SRC.format(name), timeout=60) as r, open(p, "wb") as f:
            f.write(r.read())
    with open(p) as f:
        return json.load(f)


def arcs_of(topo):
    """Decode quantized, delta-encoded arcs to lon/lat."""
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    out = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        out.append(pts)
    return out


def ring(arcs, idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def dp(pts, tol):
    """Douglas-Peucker, iterative."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x0, y0), (x1, y1) = pts[a], pts[b]
        dx, dy = x1 - x0, y1 - y0
        L = (dx * dx + dy * dy) ** 0.5
        best, bi = -1, -1
        for i in range(a + 1, b):
            x, y = pts[i]
            # a closed ring starts and ends on the same point: measure from that point instead
            d = abs(dy * (x - x0) - dx * (y - y0)) / L if L > 1e-9 else ((x - x0) ** 2 + (y - y0) ** 2) ** 0.5
            if d > best:
                best, bi = d, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def area(pts):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))) / 2


def flat(pts):
    return [v for p in pts for v in (round(p[0], 3), round(p[1], 3))]


land = fetch("land-50m")
arcs = arcs_of(land)
rings = []
for geom in land["objects"]["land"]["geometries"]:
    polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
    for poly in polys:
        for k, r in enumerate(poly):
            pts = dp(ring(arcs, r), 0.04)
            if len(pts) >= 4 and area(pts) > 0.08:
                rings.append(flat(pts))

countries = fetch("countries-50m")
carcs = arcs_of(countries)
users = {}
for gi, geom in enumerate(countries["objects"]["countries"]["geometries"]):
    polys = geom["arcs"] if geom["type"] == "MultiPolygon" else ([geom["arcs"]] if geom["type"] == "Polygon" else [])
    for poly in polys:
        for r in poly:
            for i in r:
                users.setdefault(i if i >= 0 else ~i, set()).add(gi)
borders = []
for i, g in users.items():
    if len(g) > 1:  # shared by two countries: an inland border, not a coast
        pts = dp(carcs[i], 0.04)
        if len(pts) >= 2:
            borders.append(flat(pts))

with open(os.path.join(ROOT, "data", "world.js"), "w") as f:
    f.write("// generated by prep/world.py: Natural Earth 1:50m via world-atlas@2.0.2 (public domain), lon/lat\n")
    f.write("window.WORLD = " + json.dumps({"land": rings, "borders": borders}, separators=(",", ":")) + ";\n")
print(f"world.js: {len(rings)} land rings ({sum(len(r) for r in rings) // 2} pts), {len(borders)} borders")
