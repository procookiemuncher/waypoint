"""The "Real roads" card's data: one real drive's speed over time, straight from the movement engine.

Renders a route at a fixed seed the way Spoof and the route list do (RouteRenderer, offline, road
data from the snap cache) and listens in on the drive segment: the road's speed per stretch, every
control the driver met (its own reason string: "red light, 20 s", "stop sign", "left turn, 88
deg") and the planned speed through each piece between full stops. Times are rebuilt exactly as
_emit_move steps them, then checked against the fixes it emitted.

    .venv/bin/python docs/readme/src/profile.py [route] [seed]  ->  docs/readme/data/profile.js
"""
import bisect
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "core"))
os.environ["VALHALLA_BASE_URL"] = "http://127.0.0.1:9"  # cache or bust, never the network

from backend.movement import RouteRenderer, load_route, roads, snap_route  # noqa: E402
from backend.movement import renderer as R  # noqa: E402

ROUTE = sys.argv[1] if len(sys.argv) > 1 else "faena-miami-to-liv-miami"
SEED = int(sys.argv[2]) if len(sys.argv) > 2 else 0
MPH = 2.236936

rec = {"spans": None, "controls": None, "pieces": [], "start": None, "total": None, "on": False}
_plan, _timing, _emit = roads.plan, R._timing, RouteRenderer._emit_move


def plan(edges, poly, cum, driver, rng):
    spans, controls = _plan(edges, poly, cum, driver, rng)
    if rec["on"]:
        rec["spans"], rec["controls"], rec["total"] = spans, controls, cum[-1]
    return spans, controls


def timing(ss, v):
    times = _timing(ss, v)
    if rec["on"]:
        rec["pieces"].append((list(ss), list(v), list(times)))
    return times


def emit(self, seg, start_t, *a):
    rec["on"] = seg.mode == "drive" and rec["start"] is None and bool(seg.roads)
    if rec["on"]:
        rec["start"] = start_t
    try:
        return _emit(self, seg, start_t, *a)
    finally:
        rec["on"] = False


roads.plan, R._timing, RouteRenderer._emit_move = plan, timing, emit
route, _ = snap_route(load_route(os.path.join(REPO, "core", "routes", ROUTE + ".json")))
fixes = RouteRenderer(seed=SEED).render(route)
if rec["start"] is None:
    sys.exit(f"{ROUTE} has no road-aware drive")

# the stops _emit_move split on (same rule), and the time each piece starts
total, controls = rec["total"], rec["controls"]
stops, last = [], 0.0
for c in controls:
    if c.dwell_s > 0 and c.s - last >= 1.0 and total - c.s >= 1.0:
        stops.append(c)
        last = c.s
t, curve, s_of, waits = 0.0, [], [], []
for p, (ss, v, times) in enumerate(rec["pieces"]):
    for s, vv, tt in zip(ss, v, times):
        curve.append((t + tt, vv))
        s_of.append((s, t + tt))
    t += max(1, math.ceil(times[-1]))
    if p < len(stops):
        wait = max(1, round(stops[p].dwell_s))
        waits.append((t, t + wait, stops[p].why))
        curve.append((t, 0.0))
        curve.append((t + wait, 0.0))
        t += wait
end = t
drive_fixes = [f for f in fixes if f.mode == "drive"]
drift = (drive_fixes[-1].t - rec["start"]) - end
assert abs(drift) < 1.5, f"rebuilt drive is {end:.1f} s, the fixes say {drive_fixes[-1].t - rec['start']:.1f} s"

s_pts = [s for s, _ in s_of]


def t_at(s):
    i = max(0, min(len(s_of) - 1, bisect.bisect_left(s_pts, s)))
    return s_of[i][1]


out = {
    "route": ROUTE, "seed": SEED, "seconds": round(end), "meters": round(total),
    "curve": [[round(tt, 1), round(vv * MPH, 1)] for tt, vv in sorted(curve)],
    "limits": [[round(t_at(a), 1), round(t_at(b), 1), round(v * MPH, 1)] for a, b, v in rec["spans"]],
    "waits": [[round(a, 1), round(b, 1), why] for a, b, why in waits],
    "slows": [[round(t_at(c.s), 1), c.why] for c in controls if c.dwell_s <= 0],
}
path = os.path.join(HERE, "..", "data", "profile.js")
with open(path, "w") as f:
    f.write("// generated by docs/readme/src/profile.py from the movement engine\n")
    f.write("window.PROFILE = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(f"{ROUTE} seed {SEED}: {end / 60:.1f} min drive, {total / 1609.34:.2f} mi, waits {[w[2] for w in waits]}, "
      f"{len(out['slows'])} slow-downs, top {max(v for _, v in out['curve']):.0f} mph")
